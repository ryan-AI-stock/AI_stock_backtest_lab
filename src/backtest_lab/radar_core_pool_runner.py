def _download_member_prices(
    members: list[ThemeMember],
    *,
    start_date: str,
    end_date: str,
    cache_dir: str | Path,
    cache_only: bool = False,
) -> tuple[list[ThemeMember], dict[str, pd.DataFrame], list[dict[str, str]]]:
    resolved: list[ThemeMember] = []
    prices: dict[str, pd.DataFrame] = {}
    skipped: list[dict[str, str]] = []
    for member in members:
        error_text = ""
        for ticker in _exchange_candidates(member.symbol, cache_dir):
            if cache_only:
                csv_path = Path(cache_dir) / f"{ticker.replace('.', '_')}.csv"
                if not csv_path.exists():
                    error_text = "cache_missing"
                    continue
                loaded = load_price_csv(csv_path)
                if not _covers_requested_range(loaded, start_date, end_date):
                    error_text = "cache_range_not_covered"
                    continue
                prices[ticker] = loaded
                resolved.append(replace(member, ticker=ticker))
                break
            try:
                downloaded = download_yfinance_prices([ticker], start_date=start_date, end_date=end_date, cache_dir=cache_dir)
            except Exception as error:  # noqa: BLE001 - try TW/TWO candidates before skipping.
                error_text = str(error)
                continue
            prices[ticker] = downloaded[ticker]
            resolved.append(replace(member, ticker=ticker))
            break
        else:
            skipped.append({"symbol": member.symbol, "name": member.name, "theme": member.theme, "reason": error_text})
    return resolved, prices, skipped


def _load_cached_prices(tickers: list[str], start_date: str, end_date: str, cache_dir: str | Path) -> dict[str, pd.DataFrame]:
    prices: dict[str, pd.DataFrame] = {}
    missing: list[str] = []
    for ticker in tickers:
        path = Path(cache_dir) / f"{ticker.replace('.', '_')}.csv"
        if not path.exists():
            missing.append(f"{ticker}: cache_missing")
            continue
        loaded = load_price_csv(path)
        if not _covers_requested_range(loaded, start_date, end_date):
            missing.append(f"{ticker}: cache_range_not_covered")
            continue
        prices[ticker] = loaded
    if missing:
        raise ValueError("; ".join(missing))
    return prices


def _covers_requested_range(frame: pd.DataFrame, start_date: str, end_date: str) -> bool:
    if frame.empty:
        return False
    start = pd.Timestamp(start_date)
    end = pd.Timestamp(end_date)
    start_gap_days = (frame.index.min() - start).days
    end_gap_days = (end - frame.index.max()).days
    return start_gap_days <= 10 and end_gap_days <= 10


def _exchange_candidates(symbol: str, cache_dir: str | Path) -> list[str]:
    cache_path = Path(cache_dir)
    tw = f"{symbol}.TW"
    two = f"{symbol}.TWO"
    two_cache = cache_path / f"{two.replace('.', '_')}.csv"
    tw_cache = cache_path / f"{tw.replace('.', '_')}.csv"
    if two_cache.exists() and not tw_cache.exists():
        return [two, tw]
    return [tw, two]


