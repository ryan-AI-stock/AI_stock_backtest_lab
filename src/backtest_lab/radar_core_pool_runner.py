def main() -> None:
    parser = argparse.ArgumentParser(description="Run radar core member pool v1 in resumable batches.")
    parser.add_argument("--config", default="configs/ep05_universe.json")
    parser.add_argument("--radar-root", default=DEFAULT_RADAR_ROOT)
    parser.add_argument("--start-date", default="2022-01-03")
    parser.add_argument("--end-date", default="2023-12-29")
    parser.add_argument("--warmup-start", default="2020-01-01")
    parser.add_argument("--cache-dir", default=DEFAULT_CACHE_DIR)
    parser.add_argument("--output-root", default=DEFAULT_OUTPUT_ROOT)
    parser.add_argument("--themes", default="", help="Comma-separated theme names for staged runs. Empty means all primary themes.")
    parser.add_argument("--variant-filter", default="", help="Comma-separated variant ids to run. Empty means all variants.")
    parser.add_argument("--cache-only", action="store_true", help="Use existing CSV cache only and skip missing tickers.")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    output_dir = Path(args.output_root) / "latest"
    output_dir.mkdir(parents=True, exist_ok=True)
    run_started = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    _write_step(output_dir, "load_config")

    config = load_config(args.config)
    radar_root = Path(args.radar_root)
    members = load_radar_core_members(radar_root / "data" / "theme_map.csv")
    if args.themes.strip():
        requested_themes = {theme.strip() for theme in args.themes.split(",") if theme.strip()}
        members = [member for member in members if member.theme in requested_themes]
    if not members:
        raise ValueError("No radar core members found from theme_map.csv")

    _write_step(output_dir, "download_or_load_price_cache")
    benchmark_tickers = ["0050.TW", "00631L.TW"]
    members, member_prices, skipped = _download_member_prices(
        members,
        start_date=args.warmup_start,
        end_date=args.end_date,
        cache_dir=args.cache_dir,
        cache_only=args.cache_only,
    )
    if args.cache_only:
        benchmark_prices = _load_cached_prices(benchmark_tickers, args.warmup_start, args.end_date, args.cache_dir)
    else:
        benchmark_prices = download_yfinance_prices(
            benchmark_tickers,
            start_date=args.warmup_start,
            end_date=args.end_date,
            cache_dir=args.cache_dir,
        )
    prices = {**member_prices, **benchmark_prices}
    dividends = {
        ticker: split_adjusted_dividends(prices[ticker], tuple(config.manual_splits.get(ticker, ())))
        for ticker in prices
    }

    asset_types = {ticker: "stock" for ticker in member_prices}
    asset_types.update({"0050.TW": "etf", "00631L.TW": "etf"})
    members_by_ticker = {member.ticker: member for member in members}

    _write_step(output_dir, "run_variants")
    completed = _read_completed(output_dir / "completed_variants.csv")
    variant_results: list[tuple[RadarCoreVariant, RadarCoreResult]] = []
    variant_filter = {item.strip() for item in args.variant_filter.split(",") if item.strip()}
    for variant in _variants():
        if variant_filter and variant.name not in variant_filter:
            continue
        if variant.name in completed and not args.force:
            _append_log(output_dir, variant.name, "skipped", "already_completed")
            continue
        try:
            result = simulate_radar_core_pool(
                name=variant.label,
                prices_by_ticker=member_prices,
                members_by_ticker=members_by_ticker,
                asset_types=asset_types,
                market_prices=benchmark_prices["0050.TW"],
                start_date=args.start_date,
                end_date=args.end_date,
                initial_cash=config.initial_cash_twd,
                cost_model=config.cost_model,
                variant=variant,
                dividend_series_by_ticker={ticker: dividends[ticker] for ticker in member_prices},
            )
            variant_results.append((variant, result))
            _write_variant_outputs(output_dir, variant, result)
            _append_completed(output_dir, variant, result.result)
            _append_log(output_dir, variant.name, "completed", f"return={result.result.total_return:.4f}")
        except Exception as error:  # noqa: BLE001 - runner records failures and continues.
            _append_failed(output_dir, variant, error)
            _append_log(output_dir, variant.name, "failed", str(error))

    _write_step(output_dir, "build_benchmarks")
    benchmarks = [
        simulate_buy_and_hold(
            name="0050 買進持有",
            ticker="0050.TW",
            prices=benchmark_prices["0050.TW"],
            asset_type="etf",
            start_date=args.start_date,
            end_date=args.end_date,
            initial_cash=config.initial_cash_twd,
            cost_model=config.cost_model,
            dividend_series=dividends["0050.TW"],
        ),
        simulate_buy_and_hold(
            name="0050正二 買進持有",
            ticker="00631L.TW",
            prices=benchmark_prices["00631L.TW"],
            asset_type="etf",
            start_date=args.start_date,
            end_date=args.end_date,
            initial_cash=config.initial_cash_twd,
            cost_model=config.cost_model,
            dividend_series=dividends["00631L.TW"],
        ),
    ]
    _write_summary(output_dir, variant_results, benchmarks, skipped, args, run_started)
    _write_step(output_dir, "done")
    print(f"OUTPUT_DIR={output_dir.resolve()}")


